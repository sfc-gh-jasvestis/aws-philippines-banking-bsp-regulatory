-- On-demand snapshots. No automatic freshness claim.
USE DATABASE IDENTIFIER($DEMO_DB);
USE SCHEMA CURATED;
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT unit.ID AS ENTITY_ID, unit.NAME AS ENTITY_NAME,
       unit.REGION, unit.REPORT_DOMAIN, unit.ON_REMEDIATION_PLAN, unit.STATUS,
       COUNT(*) AS EVENT_COUNT,
       SUM(observation.RECORD_COUNT) AS RECORD_COUNT,
       SUM(observation.CHECK_COUNT) AS CHECK_COUNT,
       SUM(observation.BALANCE_PHP) AS BALANCE_PHP,
       SUM(observation.EXCEPTION_COUNT) AS EXCEPTION_COUNT,
       SUM(observation.MATERIAL_ERROR_COUNT) AS MATERIAL_ERROR_COUNT,
       SUM(observation.ITEMS_ESCALATED) AS ESCALATED_COUNT,
       SUM(observation.SIGNOFF_DUE) AS SIGNOFF_DUE,
       SUM(observation.SIGNOFF_COMPLETED) AS SIGNOFF_COMPLETED,
       100.0 * SUM(observation.MATERIAL_ERROR_COUNT) / NULLIF(SUM(observation.EXCEPTION_COUNT), 0) AS EXCEPTION_PRECISION_PCT,
       100.0 * SUM(observation.SIGNOFF_COMPLETED) / NULLIF(SUM(observation.SIGNOFF_DUE), 0) AS SIGNOFF_COMPLIANCE_PCT,
       AVG(observation.LATE_FEED_PCT) AS AVG_LATE_FEED_PCT,
       MAX(observation.EVENT_DATE) AS SOURCE_WATERMARK
FROM RAW.UNIT_DAILY observation
JOIN RAW.REPORTING_UNITS unit ON unit.ID = observation.ENTITY_ID
GROUP BY unit.ID, unit.NAME, unit.REGION, unit.REPORT_DOMAIN, unit.ON_REMEDIATION_PLAN, unit.STATUS;

CREATE DYNAMIC TABLE CURATED.TREND_ANALYSIS
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT EVENT_DATE AS METRIC_DATE, COUNT(*) AS EVENT_COUNT,
       SUM(RECORD_COUNT) AS RECORD_COUNT,
       SUM(CHECK_COUNT) AS CHECK_COUNT, SUM(BALANCE_PHP) AS BALANCE_PHP,
       SUM(EXCEPTION_COUNT) AS EXCEPTION_COUNT, SUM(MATERIAL_ERROR_COUNT) AS MATERIAL_ERROR_COUNT,
       100.0 * SUM(MATERIAL_ERROR_COUNT) / NULLIF(SUM(EXCEPTION_COUNT), 0) AS EXCEPTION_PRECISION_PCT
FROM RAW.UNIT_DAILY
GROUP BY EVENT_DATE;

CREATE DYNAMIC TABLE CURATED.RULE_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
SELECT VALIDATION_RULE, SUM(EXCEPTION_COUNT) AS EXCEPTION_COUNT,
       SUM(MATERIAL_ERROR_COUNT) AS MATERIAL_ERROR_COUNT,
       SUM(ITEMS_ESCALATED) AS ESCALATED_COUNT,
       SUM(BALANCE_PHP) AS FLAGGED_BALANCE_PHP,
       100.0 * SUM(MATERIAL_ERROR_COUNT) / NULLIF(SUM(EXCEPTION_COUNT), 0) AS EXCEPTION_PRECISION_PCT
FROM RAW.UNIT_DAILY
WHERE EXCEPTION_COUNT > 0
GROUP BY VALIDATION_RULE;

CREATE DYNAMIC TABLE CURATED.KPI_SUMMARY
  TARGET_LAG = DOWNSTREAM WAREHOUSE = __DEMO_WH__
  REFRESH_MODE = FULL INITIALIZE = ON_CREATE
AS
WITH observations AS (
  SELECT SUM(EXCEPTION_COUNT) AS ALERTS, SUM(MATERIAL_ERROR_COUNT) AS CONFIRMED,
         SUM(ITEMS_ESCALATED) AS ESCALATED, SUM(BALANCE_PHP) AS NOTIONAL,
         SUM(RECORD_COUNT) AS MESSAGES,
         SUM(SIGNOFF_DUE) AS SIGNOFF_DUE, SUM(SIGNOFF_COMPLETED) AS SIGNOFF_COMPLETED,
         MAX(EVENT_DATE) AS SOURCE_WATERMARK
  FROM RAW.UNIT_DAILY
), unit_totals AS (SELECT COUNT(*) AS UNIT_COUNT FROM RAW.REPORTING_UNITS),
records AS (
  SELECT 100.0 * SUM(LEAST(MAPPED_FEEDS, REQUIRED_FEEDS)) / NULLIF(SUM(REQUIRED_FEEDS), 0) AS COVERAGE_PCT,
         SUM(PENDING_FEEDS) AS PENDING
  FROM RAW.SOURCE_FEEDS
), metrics AS (
  SELECT 1 AS SORT_ORDER, 'Exception Precision' AS TITLE,
         100.0 * CONFIRMED / NULLIF(ALERTS, 0) AS VALUE_NUM, '%' AS UNIT FROM observations
  UNION ALL SELECT 2, 'Exceptions Raised', ALERTS, '' FROM observations
  UNION ALL SELECT 3, 'Material Errors', CONFIRMED, '' FROM observations
  UNION ALL SELECT 4, 'Items Escalated', ESCALATED, '' FROM observations
  UNION ALL SELECT 5, 'Balances Validated (PHP B)', NOTIONAL / 1e9, '' FROM observations
  UNION ALL SELECT 6, 'Records Submitted', MESSAGES, '' FROM observations
  UNION ALL SELECT 7, 'Sign-off Compliance', 100.0 * SIGNOFF_COMPLETED / NULLIF(SIGNOFF_DUE, 0), '%' FROM observations
  UNION ALL SELECT 8, 'Reporting Units Monitored', UNIT_COUNT, '' FROM unit_totals
  UNION ALL SELECT 9, 'Feed Mapping Coverage', COVERAGE_PCT, '%' FROM records
  UNION ALL SELECT 10, 'Feeds Pending Mapping', PENDING, '' FROM records
)
SELECT metrics.SORT_ORDER, metrics.TITLE, metrics.VALUE_NUM,
       IFF(metrics.VALUE_NUM IS NULL, 'Unavailable',
           CASE WHEN metrics.UNIT = '' THEN TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM), '999,999,999,990'))
                ELSE TRIM(TO_VARCHAR(ROUND(metrics.VALUE_NUM, 1), '990.0')) END || metrics.UNIT) AS DISPLAY,
       'neutral' AS STATUS, observations.SOURCE_WATERMARK
FROM metrics CROSS JOIN observations;

ALTER DYNAMIC TABLE CURATED.PERFORMANCE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.TREND_ANALYSIS SUSPEND;
ALTER DYNAMIC TABLE CURATED.RULE_SUMMARY SUSPEND;
ALTER DYNAMIC TABLE CURATED.KPI_SUMMARY SUSPEND;
