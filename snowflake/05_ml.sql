-- Material-error risk scoring and exception-volume forecast over the synthetic snapshot.
-- Predicts P(material reporting error in the next 7 days) per reporting unit and
-- reports out-of-time holdout metrics; nothing is seeded as a prediction.
USE DATABASE IDENTIFIER($DEMO_DB);
USE WAREHOUSE IDENTIFIER($DEMO_WH);

CREATE VIEW ML.ERROR_FEATURES AS
SELECT r.ENTITY_ID, r.EVENT_DATE, e.REPORT_DOMAIN, e.ON_REMEDIATION_PLAN, e.YEARS_ON_PLATFORM,
       r.LATE_FEED_PCT, r.RECON_VARIANCE_RATE,
       AVG(r.LATE_FEED_PCT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW) AS LATE_FEED_7D,
       SUM(r.MATERIAL_ERROR_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 29 PRECEDING AND CURRENT ROW) AS ERRORS_30D,
       IFF(SUM(r.MATERIAL_ERROR_COUNT) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) > 0,
           'ERROR', 'OK') AS LABEL,
       COUNT(*) OVER (PARTITION BY r.ENTITY_ID ORDER BY r.EVENT_DATE ROWS BETWEEN 1 FOLLOWING AND 7 FOLLOWING) AS FUTURE_DAYS
FROM RAW.UNIT_DAILY r JOIN RAW.REPORTING_UNITS e ON e.ID = r.ENTITY_ID
-- Upstream batch delays are not unit-driven, so they are excluded from training.
WHERE r.VALIDATION_RULE <> 'Upstream batch delay';

-- Time-based split: train on older labelled days, hold out the most recent 14 labelled days.
CREATE VIEW ML.ERROR_TRAIN AS
SELECT REPORT_DOMAIN, ON_REMEDIATION_PLAN, YEARS_ON_PLATFORM, LATE_FEED_PCT, RECON_VARIANCE_RATE, LATE_FEED_7D, ERRORS_30D, LABEL
FROM ML.ERROR_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE < DATEADD('day', -21, CURRENT_DATE());

CREATE VIEW ML.ERROR_HOLDOUT AS
SELECT ENTITY_ID, EVENT_DATE, REPORT_DOMAIN, ON_REMEDIATION_PLAN, YEARS_ON_PLATFORM, LATE_FEED_PCT, RECON_VARIANCE_RATE, LATE_FEED_7D, ERRORS_30D, LABEL
FROM ML.ERROR_FEATURES
WHERE FUTURE_DAYS = 7 AND EVENT_DATE >= DATEADD('day', -21, CURRENT_DATE());

CREATE SNOWFLAKE.ML.CLASSIFICATION ML.ERROR_RISK_MODEL(
  INPUT_DATA => TABLE(ML.ERROR_TRAIN),
  TARGET_COLNAME => 'LABEL'
);

-- Out-of-time holdout: precision/recall at 0.5 versus the base rate.
CREATE TABLE ML.ERROR_RISK_HOLDOUT_METRICS AS
WITH scored AS (
  SELECT LABEL, ML.ERROR_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'REPORT_DOMAIN', REPORT_DOMAIN, 'ON_REMEDIATION_PLAN', ON_REMEDIATION_PLAN, 'YEARS_ON_PLATFORM', YEARS_ON_PLATFORM,
           'LATE_FEED_PCT', LATE_FEED_PCT, 'RECON_VARIANCE_RATE', RECON_VARIANCE_RATE,
           'LATE_FEED_7D', LATE_FEED_7D, 'ERRORS_30D', ERRORS_30D)):probability:ERROR::FLOAT AS P
  FROM ML.ERROR_HOLDOUT
)
SELECT COUNT(*) AS N,
       AVG(IFF(LABEL = 'ERROR', 1, 0)) AS BASE_RATE,
       SUM(IFF(P >= 0.5 AND LABEL = 'ERROR', 1, 0)) / NULLIF(SUM(IFF(P >= 0.5, 1, 0)), 0) AS PRECISION_AT_50,
       SUM(IFF(P >= 0.5 AND LABEL = 'ERROR', 1, 0)) / NULLIF(SUM(IFF(LABEL = 'ERROR', 1, 0)), 0) AS RECALL_AT_50,
       CURRENT_TIMESTAMP() AS EVALUATED_AT
FROM scored;

-- Latest-day score per reporting unit (label unknown, so excluded from features).
CREATE TABLE ML.ERROR_RISK_SCORES AS
WITH latest AS (
  SELECT * FROM ML.ERROR_FEATURES
  QUALIFY ROW_NUMBER() OVER (PARTITION BY ENTITY_ID ORDER BY EVENT_DATE DESC) = 1
), scored AS (
  SELECT ENTITY_ID, EVENT_DATE,
         ML.ERROR_RISK_MODEL!PREDICT(INPUT_DATA => OBJECT_CONSTRUCT(
           'REPORT_DOMAIN', REPORT_DOMAIN, 'ON_REMEDIATION_PLAN', ON_REMEDIATION_PLAN, 'YEARS_ON_PLATFORM', YEARS_ON_PLATFORM,
           'LATE_FEED_PCT', LATE_FEED_PCT, 'RECON_VARIANCE_RATE', RECON_VARIANCE_RATE,
           'LATE_FEED_7D', LATE_FEED_7D, 'ERRORS_30D', ERRORS_30D)) AS P
  FROM latest
)
SELECT ENTITY_ID, EVENT_DATE AS SCORED_AS_OF,
       ROUND(P:probability:ERROR::FLOAT, 4) AS ERROR_PROB_7D,
       CASE WHEN P:probability:ERROR::FLOAT >= 0.5 THEN 'High'
            WHEN P:probability:ERROR::FLOAT >= 0.25 THEN 'Medium' ELSE 'Low' END AS RISK_BAND,
       CURRENT_TIMESTAMP() AS SCORED_AT
FROM scored;

-- Bank-wide exception-volume forecast (14 days) from the daily series, for reporting-team staffing.
CREATE VIEW ML.DAILY_EXCEPTIONS AS
SELECT EVENT_DATE::TIMESTAMP_NTZ AS TS, SUM(EXCEPTION_COUNT)::FLOAT AS EXCEPTION_COUNT
FROM RAW.UNIT_DAILY GROUP BY EVENT_DATE;

CREATE SNOWFLAKE.ML.FORECAST ML.EXCEPTION_FORECAST_MODEL(
  INPUT_DATA => TABLE(ML.DAILY_EXCEPTIONS),
  TIMESTAMP_COLNAME => 'TS',
  TARGET_COLNAME => 'EXCEPTION_COUNT'
);

CREATE TABLE ML.EXCEPTION_FORECAST AS
SELECT TS::DATE AS FORECAST_DATE, GREATEST(0, FORECAST) AS EXCEPTION_COUNT,
       GREATEST(0, LOWER_BOUND) AS LOWER_BOUND, UPPER_BOUND
FROM TABLE(ML.EXCEPTION_FORECAST_MODEL!FORECAST(FORECASTING_PERIODS => 14));
